const camelToKebab = (str: string): string => {
  return str.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
};

export const getComponentIcon = (componentName: string): string => {
  if (!componentName) {
    return defaultIcon;
  }
  const kebabName = camelToKebab(componentName);
  return COMPONENT_ICONS[kebabName] || defaultIcon;
};

export const getDefaultComponentIcon = (): string => {
  return defaultIcon;
};
